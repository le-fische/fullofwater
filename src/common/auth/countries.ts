const countryMap = new Map<string, CountryOption>();
COUNTRIES.forEach((c) => countryMap.set(c.code.toUpperCase(), c));

export function getCountryOption(code: string): CountryOption {
  const upper = (code || '').toUpperCase().trim();
  return countryMap.get(upper) || { code: upper || 'GLOBAL', name: 'Global Racer', flag: '🌐' };
}

export function formatCountryBadge(code: string): string {
  const opt = getCountryOption(code);
  if (opt.code === 'GLOBAL' || opt.code === 'WRL' || opt.code === 'NONE') {
    return '🌐 GLOBAL';
  }
  return `${opt.flag} ${opt.code}`;
}
